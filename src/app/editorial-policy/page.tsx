import type { Metadata } from "next";
import Link from "next/link";
import { PageShell } from "@/components/page-shell";

export const metadata: Metadata = {
  title: "Editorial Policy",
  description:
    "How Toolora tool pages and guides are researched, written, tested and corrected.",
  alternates: { canonical: "/editorial-policy/" },
};

export default function EditorialPolicyPage() {
  return (
    <PageShell
      title="Editorial Policy"
      intro="Every tool page carries its own explanation, examples and limitations. This is how that content is produced and corrected."
      breadcrumbs={[{ href: "/editorial-policy/", label: "Editorial policy" }]}
      updated="2 November 2025"
    >
      <h2>Who writes the content</h2>
      <p>
        Content is written in-house by the developer who builds the tool, so the explanation and the
        implementation cannot drift apart. Pages are not outsourced to bulk content producers, and
        no page is generated by swapping a tool name into a fixed template.
      </p>

      <h2>What every tool page must contain</h2>
      <ol>
        <li>A working tool — the page is not published before the tool functions.</li>
        <li>A plain-language explanation of the problem it solves.</li>
        <li>Step-by-step instructions.</li>
        <li>The formula, rule or algorithm used, stated explicitly.</li>
        <li>At least two worked examples with real numbers or text.</li>
        <li>An honest list of limitations and assumptions.</li>
        <li>Frequently asked questions that address actual uncertainties.</li>
        <li>Links to genuinely related tools.</li>
      </ol>

      <h2>How accuracy is checked</h2>
      <ul>
        <li>
          <strong>Implementation tests.</strong> Calculation and text-processing logic is unit
          tested independently of the interface, including edge cases: zero and negative values,
          empty input, leap days, month-end dates and unicode text.
        </li>
        <li>
          <strong>Worked examples are executed.</strong> Every number shown in an example is produced
          by the same code the page runs, not written by hand.
        </li>
        <li>
          <strong>Definitions are sourced.</strong> Unit conversion factors use treaty definitions
          (for example 1 inch = 25.4 mm); statistical definitions follow standard texts; financial
          formulas are the standard annuity and compound-interest equations.
        </li>
        <li>
          <strong>Limits are stated.</strong> Where a tool cannot know something — local tax rules,
          lender fees, public holidays — the page says so instead of implying completeness.
        </li>
      </ul>

      <h2>What we will not publish</h2>
      <ul>
        <li>Tools that do not work, or that pretend to do something they do not.</li>
        <li>Pages that exist only to target a search phrase.</li>
        <li>Claimed live checks that are simulated in the browser.</li>
        <li>Health, financial or legal content presented as professional advice.</li>
      </ul>

      <h2>Corrections</h2>
      <p>
        If a result is wrong, we fix the code first and the wording second. Corrections to factual
        errors are made as soon as they are confirmed, and the page&apos;s “last reviewed” date is
        updated. Significant corrections are described in plain language on the page rather than
        silently overwritten.
      </p>
      <p>
        To report an error, use the <Link href="/contact/">contact page</Link> and include the tool
        name, the values you entered, and the result you expected.
      </p>

      <h2>Independence</h2>
      <p>
        Recommendations are based on usefulness, not on commercial relationships. If the site ever
        uses affiliate links, they will be disclosed on the page where they appear and will never
        influence which tools we build or how results are presented.
      </p>

      <h2>Advertising and editorial separation</h2>
      <p>
        Advertising, if enabled, is clearly labelled and kept outside tool controls and results. It
        does not influence tool content, and no advertiser can pay for a favourable recommendation.
      </p>
    </PageShell>
  );
}
